# CoreLogic Studio - Safe Startup Script
# Handles Python compatibility issues gracefully

Write-Host "??????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?           CoreLogic Studio - Safe Startup Mode                ?" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$ProjectDir = "I:\ashesinthedawn"
Set-Location $ProjectDir

# Check Python version
Write-Host "?? Checking Python version..." -ForegroundColor Yellow
try {
    $pythonVersion = python --version 2>&1
    Write-Host "   Found: $pythonVersion" -ForegroundColor Gray
    
    if ($pythonVersion -like "*3.13*") {
        Write-Host ""
        Write-Host "??  WARNING: Python 3.13 detected" -ForegroundColor Yellow
        Write-Host "   • scipy has compatibility issues with Python 3.13" -ForegroundColor Gray
        Write-Host "   • Python DSP effects will NOT be available" -ForegroundColor Gray
        Write-Host "   • Web Audio effects (7) will work fine" -ForegroundColor Gray
        Write-Host ""
        Write-Host "   Recommended: Use Python 3.11 for full DSP support" -ForegroundColor Cyan
        Write-Host "   See FIX_PYTHON_COMPATIBILITY.md for details" -ForegroundColor Cyan
        Write-Host ""
        
        $response = Read-Host "Continue without Python DSP? (Y/n)"
        if ($response -eq "n" -or $response -eq "N") {
            Write-Host ""
            Write-Host "Startup cancelled. Please install Python 3.11 and try again." -ForegroundColor Red
            Write-Host "See FIX_PYTHON_COMPATIBILITY.md for instructions." -ForegroundColor Yellow
            exit 0
        }
    } else {
        Write-Host "   ? Python version is compatible" -ForegroundColor Green
    }
} catch {
    Write-Host "   ??  Could not detect Python version" -ForegroundColor Yellow
}

Write-Host ""

# Start Python Server
Write-Host "?? Starting Python Server (Fallback Mode)..." -ForegroundColor Magenta
Start-Process powershell -ArgumentList @(
    "-NoExit",
    "-Command",
    @"
Set-Location '$ProjectDir'
. .\venv\Scripts\Activate.ps1
Write-Host '??????????????????????????????????????????????????????????????????' -ForegroundColor Magenta
Write-Host '?              Python Server (Safe Mode)                         ?' -ForegroundColor Magenta
Write-Host '??????????????????????????????????????????????????????????????????' -ForegroundColor Magenta
Write-Host ''
Write-Host '??  Starting server...' -ForegroundColor Yellow
Write-Host ''
Write-Host 'Note: If you see "DSP effects not available" - this is expected' -ForegroundColor Gray
Write-Host '      Server will work fine with Web Audio only mode' -ForegroundColor Gray
Write-Host ''
python codette_server_unified.py
"@
)

Start-Sleep -Seconds 3

# Start React Frontend
Write-Host "? Starting React Frontend..." -ForegroundColor Cyan
Start-Process powershell -ArgumentList @(
    "-NoExit",
    "-Command",
    @"
Set-Location '$ProjectDir'
Write-Host '??????????????????????????????????????????????????????????????????' -ForegroundColor Cyan
Write-Host '?           React Frontend (Vite Dev Server)                     ?' -ForegroundColor Cyan
Write-Host '??????????????????????????????????????????????????????????????????' -ForegroundColor Cyan
Write-Host ''
Write-Host '? Starting Vite...' -ForegroundColor Yellow
Write-Host ''
npm run dev
"@
)

Start-Sleep -Seconds 2

Write-Host ""
Write-Host "??????????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host "?                    Services Starting...                        ?" -ForegroundColor Green
Write-Host "??????????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host ""
Write-Host "?? Python Server: " -NoNewline -ForegroundColor White
Write-Host "http://localhost:8000 " -NoNewline -ForegroundColor Yellow
Write-Host "(Safe Mode)" -ForegroundColor Gray
Write-Host "?? React Frontend: " -NoNewline -ForegroundColor White
Write-Host "http://localhost:5173" -ForegroundColor Cyan
Write-Host ""
Write-Host "?? Status:" -ForegroundColor Yellow
Write-Host "   • Server: Starting (check Python window)" -ForegroundColor Gray
Write-Host "   • Frontend: Starting (check Vite window)" -ForegroundColor Gray
Write-Host "   • Python DSP: May be unavailable (this is OK)" -ForegroundColor Gray
Write-Host ""
Write-Host "?? What to expect:" -ForegroundColor Yellow
Write-Host "   • Python DSP button shows red dot (offline)" -ForegroundColor Gray
Write-Host "   • 7 Web Audio effects available (works great!)" -ForegroundColor Gray
Write-Host "   • Full DAW functionality otherwise" -ForegroundColor Gray
Write-Host ""
Write-Host "?? For full Python DSP support:" -ForegroundColor Cyan
Write-Host "   See FIX_PYTHON_COMPATIBILITY.md" -ForegroundColor Cyan
Write-Host ""
Write-Host "Press any key to close this window (servers will keep running)..." -ForegroundColor DarkGray
$null = $Host.UI.RawUI.ReadKey("NoEcho,IncludeKeyDown")
